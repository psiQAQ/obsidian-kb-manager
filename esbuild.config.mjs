import esbuild from 'esbuild';
import esbuildSvelte from 'esbuild-svelte';
import process from 'process';
import { readFileSync, readdirSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const upstreamLicense = readFileSync(new URL('./assets/licenses/obsidian-git.txt', import.meta.url), 'utf8');
const banner = `/*
Portions adapted from Obsidian Git 2.43.0
${upstreamLicense}
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';

const skeletonPaths = [
  ".gitignore",
  "AGENTS.md",
  "Clippings/.gitkeep",
  "LICENSES.md",
  "Notes/.gitkeep",
  "README.md",
  "kb.toml",
  "knowledge.base",
  "raw/.gitkeep",
  "reports/.gitkeep",
  "Templates/Bases/分类专用模板.base",
  "Templates/人工笔记模板.md",
  "Templates/分类入口模板.md",
  "Templates/归档模板.md",
  "Templates/新来源模板.md",
  "Templates/知识页面模板.md",
  "Templates/资料摘要模板.md",
  "wiki/index.md",
  "wiki/log.md",
  "wiki/overview.md"
];

function inspectSkeleton(relative = '') {
	const dir = new URL('./assets/llm-wiki/' + relative, import.meta.url);
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const name = relative + entry.name;
		if (entry.isDirectory() && skeletonPaths.some(file => file.startsWith(name + '/'))) {
			inspectSkeleton(name + '/');
		} else if (!entry.isFile() || !skeletonPaths.includes(name)) {
			throw new Error('Unexpected built-in template resource: ' + name);
		}
	}
}
inspectSkeleton();
const skeleton = skeletonPaths.map(name => [name, readFileSync(new URL('./assets/llm-wiki/' + name, import.meta.url), 'utf8')]);

function readKepano(relative = '') {
	const root = fileURLToPath(new URL('./assets/kepano/', import.meta.url));
	const files = [];
	for (const entry of readdirSync(join(root,relative), {withFileTypes: true})) {
		const name = relative + entry.name;
		if (entry.isDirectory() && !entry.name.startsWith('.')) {
			files.push(...readKepano(name + '/'));
		} else if (entry.isFile() && (/\.(?:md|base)$/iu.test(entry.name) || entry.name === '.gitkeep')) {
			files.push([name, readFileSync(join(root,name),'utf8')]);
		} else {
			throw new Error('Unexpected Kepano template resource: ' + name);
		}
	}
	return files;
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	stdin: {
		contents: `const platform = require('obsidian').Platform;
module.exports = platform.isMobile ? require('./src/mobile/plugin.ts').default : require('./src/main.ts').default;`,
		resolveDir: fileURLToPath(new URL('.', import.meta.url)),
		sourcefile: 'platform-entry.cjs',
	},
	bundle: true,
	platform: 'browser',
	alias: {buffer:'buffer/'},
	conditions: ['browser', prod ? 'production' : 'development'],
	plugins: [
		esbuildSvelte({compilerOptions: {css: 'injected'}}),
		// isomorphic-git's browser module expects Buffer. Scope the shim to that module.
		{name:'mobile-git-buffer',setup(build) {
			build.onLoad({filter:/[\\/]isomorphic-git[\\/]index\.js$/}, ({path}) => ({
				contents: "import { Buffer } from 'buffer/';\n" + readFileSync(path,'utf8'),
				resolveDir: dirname(path), loader:'js', watchFiles:[path],
			}));
		}},
	],
	metafile: prod,
	define: {
		KB_BUILTIN: JSON.stringify(Object.fromEntries(skeleton)),
		KB_KEPANO: JSON.stringify(Object.fromEntries(readKepano())),
	},
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		'node:*',
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	const result = await context.rebuild();
	mkdirSync('dist', { recursive: true });
	writeFileSync('dist/build-inputs.json', JSON.stringify(result.metafile));
	process.exit(0);
} else {
	await context.watch();
}
