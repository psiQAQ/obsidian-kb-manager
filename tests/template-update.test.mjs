import assert from 'node:assert/strict';
import test from 'node:test';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import { digest } from '../src/fs/vault.ts';
import { discover, readManifest, writeIdentity } from '../src/kb/catalog.ts';
import { createLibrary, previewCreate } from '../src/kb/create.ts';
import { initialIdentityDefaults } from '../src/git/initial.ts';
import { applyTemplateUpdate, previewTemplateUpdate } from '../src/kb/template-update.ts';
import { vaultDisk } from './fixtures/vault-disk.mjs';

test('managed template updates render per instance and preserve edits, missing files and notes',async t=>{
	const scratch=path.resolve('.tmp');
	await fs.mkdir(scratch,{recursive:true});
	const root=await fs.mkdtemp(path.join(scratch,'template-update-'));
	assert.equal(path.dirname(root),scratch);
	t.after(()=>fs.rm(root,{recursive:true,force:true}));
	const disk=vaultDisk(root,'.settings');
	const source='样板/阅读手记',sourceDir=await disk.path(source);
	const config={parents:['书架'],templates:[source]};
	const card='Templates/读书卡.md',legacy='Templates/旧版.md',removed='Templates/停用.md',added='Templates/新增.md';
	const reference='Templates/参考.md';
	const original='[[{{kb_root}}/首页]]\n\n## 阅读\n';
	const draft='## 读书笔记\n';
	const host={version:'3.4.0',pluginVersion:()=>undefined};
	await fs.mkdir(path.join(sourceDir,'Templates'),{recursive:true});
	const sourceVersion=async(version,files)=>{
		const spec={protocolVersion:1,id:'reading-example',version,managedFiles:files,text:{[card]:['kb_root'],[removed]:['kb_root']}};
		await fs.writeFile(path.join(sourceDir,'kb-template.json'),JSON.stringify(spec));
	};
	await sourceVersion('1',[card,legacy,removed,reference]);
	await fs.writeFile(path.join(sourceDir,card),original);
	await fs.writeFile(path.join(sourceDir,legacy),'legacy\n');
	await fs.writeFile(path.join(sourceDir,removed),'keep older copy in {{kb_root}}\n');
	await fs.writeFile(path.join(sourceDir,reference),'old reference\n');
	const git={defaults:await initialIdentityDefaults(),values:{name:'QA',email:'qa@example.invalid'},origin:''};
	for(const name of ['甲','乙']){
		const input={parent:'书架',name,displayName:name,description:'阅读手记',source,git};
		await createLibrary(disk,config,await previewCreate(disk,config,input,{}),{});
	}
	const libraries=await discover(disk,config);
	const first=libraries.find(lib=>lib.location==='书架/甲'),second=libraries.find(lib=>lib.location==='书架/乙');
	assert.notEqual(first.identity.id,second.identity.id);
	const read=async(lib,file)=>fs.readFile(await disk.path(lib.location+'/'+file),'utf8');
	const write=async(lib,file,content)=>fs.writeFile(await disk.path(lib.location+'/'+file),content);
	const firstOriginal=await read(first,card),secondOriginal=await read(second,card);
	assert.equal(firstOriginal,original.replace('{{kb_root}}',first.location));
	assert.equal(secondOriginal,original.replace('{{kb_root}}',second.location));
	assert.equal(first.templateFiles.digests[card],digest(firstOriginal));
	assert.equal(second.templateFiles.digests[card],digest(secondOriginal));
	assert.notEqual(first.templateFiles.digests[card],second.templateFiles.digests[card]);
	assert.ok(first.identity.managed.some(file=>file.path===removed));
	assert.ok(!first.identity.managed.some(file=>file.path===card));
	const currentManifest=await read(first,'kb.toml');
	const legacyIdentity=readManifest(currentManifest).identity;
	legacyIdentity.managed.push({path:card,root:first.location,role:'template-root',offsets:[firstOriginal.indexOf(first.location)],
		fingerprint:digest(firstOriginal)});
	await write(first,'kb.toml',writeIdentity(currentManifest,legacyIdentity));
	const legacyLibrary=(await discover(disk,config)).find(lib=>lib.location===first.location);
	await write(first,'自己的笔记.md',draft);
	await write(second,card,secondOriginal+'我的批注\n');
	await fs.unlink(await disk.path(second.location+'/'+legacy));
	await write(second,added,'我自己的同名文件\n');
	await sourceVersion('2',[card,legacy,added,reference]);
	const updated='## 前言\n\n'+original+'## 引文\n';
	await fs.writeFile(path.join(sourceDir,card),updated);
	await fs.writeFile(path.join(sourceDir,legacy),'new release\n');
	await fs.writeFile(path.join(sourceDir,added),'new file\n');
	await fs.writeFile(path.join(sourceDir,reference),'new reference\n');
	const plan=await previewTemplateUpdate(disk,config,legacyLibrary,source,host);
	assert.deepEqual(Object.fromEntries(plan.files.map(file=>[file.path,file.change])),{[card]:'replace',[legacy]:'replace',[added]:'add',[reference]:'replace',[removed]:'retained'});
	assert.equal(plan.canApply,true);
	assert.equal(await read(first,card),firstOriginal);
	assert.equal(readManifest(await read(first,'kb.toml')).identity.managed.some(file=>file.path===card),true);
	await assert.rejects(applyTemplateUpdate(disk,config,plan,host,()=>{throw new Error('open editor has unsaved changes');}),/unsaved/u);
	assert.equal(await read(first,card),firstOriginal);
	await fs.writeFile(path.join(sourceDir,card),'external edit\n');
	await assert.rejects(applyTemplateUpdate(disk,config,plan,host),/changed|已变化/u);
	assert.equal(await read(first,card),firstOriginal);
	await fs.writeFile(path.join(sourceDir,card),updated);
	await applyTemplateUpdate(disk,config,plan,host);
	assert.equal(await read(first,card),updated.replace('{{kb_root}}',first.location));
	assert.equal(await read(first,'自己的笔记.md'),draft);
	assert.equal(await read(first,added),'new file\n');
	assert.equal(await read(first,removed),'keep older copy in '+first.location+'\n');
	const after=readManifest(await read(first,'kb.toml'));
	assert.equal(after.templateFiles.version,'2');
	assert.equal(after.identity.template.version,'1');
	assert.equal(after.templateFiles.digests[card],digest(await read(first,card)));
	assert.equal(after.templateFiles.digests[removed],undefined);
	assert.equal(after.identity.managed.some(file=>file.path===removed),false);
	assert.equal(after.identity.managed.some(file=>file.path===card),false);
	const conflict=await previewTemplateUpdate(disk,config,second,source,host);
	assert.deepEqual(Object.fromEntries(conflict.files.map(file=>[file.path,file.change])),{[card]:'conflict',[legacy]:'missing',[added]:'conflict',[reference]:'replace',[removed]:'retained'});
	assert.equal(conflict.canApply,true);
	await applyTemplateUpdate(disk,config,conflict,host);
	assert.equal(await read(second,card),secondOriginal+'我的批注\n');
	assert.equal(await read(second,added),'我自己的同名文件\n');
	assert.equal(await read(second,reference),'new reference\n');
	assert.equal(readManifest(await read(second,'kb.toml')).templateFiles.version,'1');
	await assert.rejects(read(second,legacy),{code:'ENOENT'});
	await sourceVersion('3',[card,legacy,added,reference,removed]);
	const current=(await discover(disk,config)).find(lib=>lib.location===first.location);
	const reintroduced=await previewTemplateUpdate(disk,config,current,source,host);
	assert.equal(reintroduced.files.find(file=>file.path===removed).change,'conflict');
	assert.equal(reintroduced.canApply,false);
	assert.equal(await read(first,removed),'keep older copy in '+first.location+'\n');
});
