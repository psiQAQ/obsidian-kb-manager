import test from 'node:test';
import {hunkLines} from '../src/git/hunk-lines.ts';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import * as path from 'node:path';
import {execFileSync} from 'node:child_process';
import {initializeRepository} from '../src/git/repository.ts';
import {previewVersion,saveVersion} from '../src/git/versions.ts';
import {changeIndex,fileComparison,changeIndexHunk,textHunks,reverseWorkHunk,editorIndexBase,verifyWorkingFile} from '../src/git/index-actions.ts';
