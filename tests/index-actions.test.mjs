test('staging and comparing files preserves sibling and parent indexes and partially staged bytes',async t=>{
	await fs.mkdir('.tmp',{recursive:true});
	const root=await fs.mkdtemp(path.resolve('.tmp','source-control-'));
	t.after(()=>fs.rm(root,{force:true,recursive:true}));
	const first=path.join(root,'one'), second=path.join(root,'two');
	const file='same.md';
	const native=(location,...args)=>execFileSync('git',['-C',location,...args]);
	const readIndex=location=>fs.readFile(path.join(location,'.git/index'));
	for(const dir of [root,first,second]){
		await fs.mkdir(dir,{recursive:true});
		await initializeRepository(dir);
		await fs.writeFile(path.join(dir,file),'original');
		const unborn=await previewVersion(dir);
		await changeIndex(dir,unborn,'stage',[file]);
		assert.equal(native(dir,'show',':'+file).toString(),'original');
		await changeIndex(dir,await previewVersion(dir),'unstage',[file]);
		assert.equal(native(dir,'ls-files').length,0);
		await saveVersion(dir,await previewVersion(dir),'initial',{name:'Test',email:'test@example.invalid'});
	}
	const rootIndex=await readIndex(root), siblingIndex=await readIndex(second);
	await fs.writeFile(path.join(first,file),'index');
	native(first,'add','--',file);
	await fs.writeFile(path.join(first,file),'working');
	await fs.writeFile(path.join(first,'attachment'),Buffer.from([0,255,10]));
	const partial=await previewVersion(first);
	const staged=await fileComparison(first,partial,file,true);
	assert.equal(Buffer.from(staged.before).toString(),'original');
	assert.equal(Buffer.from(staged.after).toString(),'index');
	const unstaged=await fileComparison(first,partial,file,false);
	assert.equal(Buffer.from(unstaged.before).toString(),'index');
	assert.equal(Buffer.from(unstaged.after).toString(),'working');
	await changeIndex(first,partial,'stage',['attachment']);
	assert.equal(native(first,'show',':'+file).toString(),'index');
	assert.deepEqual(native(first,'show',':attachment'),Buffer.from([0,255,10]));
	await assert.rejects(changeIndex(first,partial,'stage',[file]),/changed/);
	const before=await readIndex(first);
	await assert.rejects(changeIndex(first,await previewVersion(first),'stage',['../same.md']),/Select files/);
	assert.deepEqual(await readIndex(first),before);
	await changeIndex(first,await previewVersion(first),'unstage',[file]);
	assert.equal(native(first,'show',':'+file).toString(),'original');
	assert.equal(await fs.readFile(path.join(first,file),'utf8'),'working');
	await fs.unlink(path.join(first,file));
	await changeIndex(first,await previewVersion(first),'stage',[file]);
	assert.equal(native(first,'ls-files','--',file).length,0);
	await changeIndex(first,await previewVersion(first),'unstage',[file]);
	assert.equal(native(first,'show',':'+file).toString(),'original');
	assert.deepEqual(await readIndex(root),rootIndex);
	assert.deepEqual(await readIndex(second),siblingIndex);
});

test('hunk stage and unstage preserve CRLF, BOM and remaining worktree bytes; history works with conflicted index',async t=>{
	await fs.mkdir('.tmp',{recursive:true});
	const dir=await fs.mkdtemp(path.resolve('.tmp','source-hunk-'));
	t.after(()=>fs.rm(dir,{force:true,recursive:true}));
	await initializeRepository(dir);
	const target=path.join(dir,'target.md');
	const original='\uFEFF'+Array.from({length:25},(_,i)=>'line '+i).join('\r\n')+'\r\n';
	await fs.writeFile(target,original);
	const author={name:'Test',email:'test@example.invalid'};
	const first=await saveVersion(dir,await previewVersion(dir),'first',author);
	assert.equal((await commitFiles(dir,first)).files[0].file,'target.md');
	const staged=original.replace('line 0','first edit'), work=staged.replace('line 22','second edit');
	await fs.writeFile(target,work);
	const native=(...args)=>execFileSync('git',['-C',dir,...args]).toString();
	const preview=await previewVersion(dir);
	const {before,after}=await fileComparison(dir,preview,'target.md',false);
	assert.equal(textHunks(before,after).patch.hunks.length,2);
	assert.equal(Buffer.from(await editorIndexBase(dir,'target.md')).toString(),original);
	assert.equal(reverseWorkHunk(before,after,1),staged);
	await changeIndexHunk(dir,preview,'stage','target.md',0);
	assert.equal(native('show',':target.md'),staged);
	await changeIndexHunk(dir,await previewVersion(dir),'unstage','target.md',0);
	assert.equal(native('show',':target.md'),original);
	assert.equal(await fs.readFile(target,'utf8'),work);
	const second=await saveVersion(dir,await previewVersion(dir),'second',author);
	const delta=await committedComparison(dir,second,'target.md');
	assert.equal(Buffer.from(delta.before).toString(),original);
	assert.equal(Buffer.from(delta.after).toString(),work);
	const oid=native('rev-parse','HEAD:target.md').trim();
	execFileSync('git',['-C',dir,'update-index','--index-info'],{input:'0 '+'0'.repeat(40)+'\ttarget.md\n100644 '+oid+' 2\ttarget.md\n100644 '+oid+' 3\ttarget.md\n'});
	assert.deepEqual(await conflictFiles(dir),['target.md']);
	await assert.rejects(previewVersion(dir),/conflicted/);
	assert.equal((await commitFiles(dir,second)).files.length,1);
});

test('amend replaces only the tip and uses the previously staged bytes',async t=>{
	await fs.mkdir('.tmp',{recursive:true});
	const dir=await fs.mkdtemp(path.resolve('.tmp','source-amend-'));
	t.after(()=>fs.rm(dir,{recursive:true,force:true}));
	const author={name:'First Author',email:'first@example.invalid'}, name='a.md';
	const native=(...args)=>execFileSync('git',['-C',dir,...args]).toString().trim();
	await initializeRepository(dir);
	const file=path.join(dir,name);
	await fs.writeFile(file,'one');
	const root=await saveVersion(dir,await previewVersion(dir),'first',author);
	await fs.writeFile(file,'two');
	const previous=await saveVersion(dir,await previewVersion(dir),'second',author);
	await fs.writeFile(file,'staged');
	await changeIndex(dir,await previewVersion(dir),'stage',[name]);
	await fs.writeFile(file,'worktree');
	const saved=await saveVersion(dir,await previewVersion(dir),'amended',{name:'Editor',email:'editor@example.invalid'},undefined,'amend');
	assert.notEqual(saved,previous);
	assert.equal(native('rev-parse','HEAD^'),root);
	assert.equal(native('show','-s','--format=%an/%cn'), 'First Author/Editor');
	assert.equal(native('show','HEAD:'+name),'staged');
	assert.equal(await fs.readFile(file,'utf8'),'worktree');
	await assert.rejects(saveVersion(dir,await previewVersion(dir),'staged only',author,undefined,'staged'),/暂存|Stage/);
});

test('source control rejects ambiguous refs, unsafe editor paths and multiply linked worktree files',async t=>{
	await fs.mkdir('.tmp',{recursive:true});
	const dir=await fs.mkdtemp(path.resolve('.tmp','source-bound-'));
	t.after(()=>fs.rm(dir,{recursive:true,force:true}));
	await initializeRepository(dir);
	await fs.writeFile(path.join(dir,'a.md'),'note');
	await assert.rejects(editorIndexBase(dir,'../a.md'),/Invalid/);
	await fs.link(path.join(dir,'a.md'),path.join(dir,'linked.md'));
	await assert.rejects(verifyWorkingFile(dir,'linked.md'),/Linked/);
	const ref=path.join(dir,'.git','refs','heads','main');
	await fs.mkdir(path.dirname(ref),{recursive:true});
	await fs.writeFile(ref,'ref: HEAD\n');
	await assert.rejects(previewVersion(dir),/Invalid local Git reference/);
	await fs.unlink(ref);
	await fs.writeFile(path.join(dir,'.git','packed-refs'),'bogus refs/heads/main\n');
	await assert.rejects(previewVersion(dir),/Invalid local Git reference/);
});

test('editor line counts distinguish replacements and independent edit runs',()=>{
	const {counts,marks}=hunkLines({newStart:3,lines:[' keep','-a','-b','+A','+B',' unchanged','-gone',' context','+new','+end']});
	assert.deepEqual(counts,{added:2,changed:2,deleted:1});
	assert.deepEqual([...marks],[[4,'~'],[5,'~'],[7,'−'],[8,'+'],[9,'+']]);
});
