import test from 'node:test';
import assert from 'node:assert/strict';
import * as fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {initializeRepository} from '../src/git/repository.ts';
import {previewVersion,saveVersion,history} from '../src/git/versions.ts';

test('native Git interoperates with previews, partially staged bytes, delete and history pages',async t=>{
	await fs.mkdir('.tmp',{recursive:true});
	const dir=await fs.mkdtemp(path.resolve('.tmp','versions-'));
	t.after(()=>fs.rm(dir,{recursive:true,force:true}));
	const run=(...args)=>execFileSync('git',['-C',dir,...args]);
	const index=path.join(dir,'.git/index'),file=path.join(dir,'note.md');
	await initializeRepository(dir);
	run('config','core.autocrlf','false');
	run('config','user.name','Local');run('config','user.email','local@example.invalid');
	assert.equal((await history(dir)).entries.length,0);
	await fs.writeFile(file,Buffer.from([239,187,191,65,13,10]));
	await fs.writeFile(path.join(dir,'.gitignore'),'ignored\n');
	await fs.writeFile(path.join(dir,'ignored'),'private');
	const first=await previewVersion(dir);
	assert.ok(!first.changes.some(c=>c.file==='ignored'));
	const oid=await saveVersion(dir,first,'initial');
	assert.deepEqual(run('show','HEAD:note.md'),await fs.readFile(file));
	assert.equal((await previewVersion(dir)).changes.length,0);
	await assert.rejects(saveVersion(dir,await previewVersion(dir),'empty'),/没有/);
	await fs.writeFile(file,'staged');run('add','note.md');
	await fs.writeFile(file,'working');
	const bytes=await fs.readFile(index);
	const partial=await previewVersion(dir);
	assert.ok(partial.staged);
	assert.deepEqual(await fs.readFile(index),bytes);
	let proposed;
	await assert.rejects(saveVersion(dir,partial,'index only',receipt=>{
		if(receipt.candidate)proposed=receipt.candidate;
		if(receipt.committed)throw new Error('simulated loss of completion acknowledgement');
		return Promise.resolve();
	}),/completion acknowledgement/);
	assert.equal(run('rev-parse','HEAD').toString().trim(),proposed);
	await assert.rejects(saveVersion(dir,partial,'index only'),/变化/);
	assert.equal(run('show','HEAD:note.md').toString(),'staged');
	assert.equal(await fs.readFile(file,'utf8'),'working');
	const stale=await previewVersion(dir);
	await fs.writeFile(file,'changed after preview');
	await assert.rejects(saveVersion(dir,stale,'stale'),/变化/);
	await fs.unlink(file);
	const deletion=await previewVersion(dir);
	assert.ok(deletion.changes.some(c=>c.file==='note.md' && c.work===0));
	await saveVersion(dir,deletion,'remove note');
	const page=await history(dir,undefined,2);
	assert.equal(page.entries.length,2);
	assert.equal((await history(dir,page.next,2)).entries[0].oid,oid);
	assert.equal(run('ls-tree','--name-only','HEAD').toString().trim(),'.gitignore');
	await fs.writeFile(path.join(dir,'.git/index.lock'),'');
	await assert.rejects(previewVersion(dir),/index.lock/);
	assert.equal((await history(dir)).entries.length,3);
});
